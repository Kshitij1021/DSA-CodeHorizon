#include<iostream>                      // header file for cin, cout functions
#include<cmath>                         // header file for mathematical functions
using namespace std;

int main()
{
    // Max Func fftion
    cout<<max(56, 87)<<endl;

    // Min Function
    cout<<min(74, 95)<<endl;

    // Max, Min functions valid for only two arguments


    // Power Function
    cout<<pow(2, 7)<<endl;                // --> Gives output 2 raised power 7
    cout<<pow(2.7, 2.9)<<endl;

    // Square Root Function
    cout<<sqrt(64)<<endl;
    cout<<sqrt(81.9)<<endl;
    
    // Cube Root Function
    cout<<cbrt(343)<<endl;
    cout<<cbrt(81.9)<<endl;

    // Modulus Function
    cout<<abs(-543)<<endl;
}